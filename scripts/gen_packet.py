#!/usr/bin/env python3
"""Generate the access-gate packet artifact header from the packet artifact JSON.

The script validates the committed JSON schema and emits the generated C
header consumed by the embedded firmware. A freshness check can compare
the generated header with the committed include/packet_artifact.h.
"""

import argparse
import json
import sys
from pathlib import Path

ARTIFACT_FORMAT = "access-gate-packets-demo-v1"
DEFAULT_OUTPUT_HEADER = "include/packet_artifact.h"

_FROM_JSON_HELP = (
    "Load existing JSON artifact and emit header without fresh encoding"
)
_HEADER_OUT_HELP = "Output generated C header path"
_CHECK_HEADER_HELP = (
    "Optional path to compare against generated header and fail if stale"
)
_INVALID_JSON = "Artifact JSON at {0} is invalid JSON."
_FORMAT_MISMATCH = (
    "Artifact format must be '{0}', got '{1}'."
)
_FRAME_TOO_LONG = (
    "Example frame must encode to at most frame_size bytes."
)

